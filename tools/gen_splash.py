"""The power-on picture (spec/prds/0002-funky-monkey-splash.md), packed for ui_draw.c splash_draw (run by
tools/build.py generate()).

  gen_splash.py OUT.h [PNG]          PNG: assets/splash.png

The PNG is the finished picture: 120 x 120, at most 16 colours (edit it in a pixel editor). The firmware draws each
pixel 2 x 2. It was made from the supplied 2000 x 2000 picture: white border cropped, centre square, LANCZOS to
120 x 120, Pillow quantize(16, MEDIANCUT, no dither, kmeans=8).

Output:
  SPLASH_PAL   16 colours, RGB565
  SPLASH_PX    4 bits per pixel, the left pixel in the high nibble, rows back to back
"""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
W = H = 120


def main():
    out = Path(sys.argv[1])
    src = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "assets" / "splash.png"
    im = Image.open(src)
    if im.size != (W, H):
        raise SystemExit(f"gen_splash: {src} is {im.size[0]} x {im.size[1]}, not {W} x {H}")
    rgb = im.convert("RGB")
    cols = rgb.getcolors(16)
    if cols is None:
        raise SystemExit(f"gen_splash: {src} has more than 16 colours")
    pal = sorted(c for _, c in cols) + [(0, 0, 0)] * (16 - len(cols))
    idx = [pal.index(c) for c in rgb.get_flattened_data()]
    px = bytes(idx[i] << 4 | idx[i + 1] for i in range(0, W * H, 2))
    p565 = [(r >> 3) << 11 | (g >> 2) << 5 | b >> 3 for r, g, b in pal]
    rows = ",\n".join("    " + ", ".join(f"0x{b:02X}" for b in px[i:i + 20]) for i in range(0, len(px), 20))
    out.write_text(
        f"/* generated by tools/gen_splash.py from {src.name}: do not edit */\n"
        f"#define SPLASH_W {W}u\n#define SPLASH_H {H}u\n"
        "static const uint16_t SPLASH_PAL[16] = {" + ", ".join(f"0x{v:04X}" for v in p565) + "};\n"
        f"static const uint8_t SPLASH_PX[{len(px)}] = {{\n{rows}}};\n")
    print(f"gen_splash: {out.name} {len(px) + 32} B")


if __name__ == "__main__":
    main()
